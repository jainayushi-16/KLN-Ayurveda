export function getHindiTranslation(product) {
  if (!product) return null;
  const pId = String(product.id || product._id || "").toLowerCase();
  const pSlug = String(product.slug || "").toLowerCase();
  const pName = String(product.name || "").toLowerCase();
  const pType = String(product.type || "").toLowerCase();

  // 1. Direct match by ID
  if (HINDI_PRODUCT_MAP[product.id]) return HINDI_PRODUCT_MAP[product.id];
  if (HINDI_PRODUCT_MAP[pId]) return HINDI_PRODUCT_MAP[pId];
  if (pSlug && HINDI_PRODUCT_MAP[pSlug]) return HINDI_PRODUCT_MAP[pSlug];

  // 2. Combo match rules
  if (pId.includes("combo-oil-tonic") || (pName.includes("tonic") && (pName.includes("buy 1") || pName.includes("bogo") || pName.includes("combo")))) {
    return HINDI_PRODUCT_MAP["kln-combo-oil-tonic-01"];
  }
  if (pId.includes("combo-oil-mask") || (pName.includes("mask") && (pName.includes("complete") || pName.includes("combo")))) {
    return HINDI_PRODUCT_MAP["kln-combo-oil-mask-02"];
  }

  // 3. Single product match rules
  if (pName.includes("mask") || pType.includes("mask") || pId.includes("mask")) {
    return HINDI_PRODUCT_MAP["kln-hair-mask-05"];
  }
  if (pName.includes("tonic") || pType.includes("tonic") || pId.includes("tonic")) {
    return HINDI_PRODUCT_MAP["kln-hair-tonic-03"];
  }
  if (pName.includes("oil") || pType.includes("oil") || pId.includes("oil")) {
    return HINDI_PRODUCT_MAP["kln-hair-oil-01"];
  }

  return null;
}

export function getLocalizedProduct(product, isHindi) {
  if (!product) return product;
  if (!isHindi) return product;

  const hindiData = getHindiTranslation(product);
  if (!hindiData) return product;

  return {
    ...product,
    name: hindiData.name || product.name,
    shortDesc: hindiData.shortDesc || product.shortDesc,
    fullDesc: hindiData.fullDesc || product.fullDesc,
    badge: hindiData.badge || product.badge,
    category: hindiData.category || product.category,
    type: hindiData.type || product.type,
    benefits: hindiData.benefits || product.benefits,
    usageInstructions: hindiData.usageInstructions || product.usageInstructions,
    caution: hindiData.caution || product.caution,
    specs: hindiData.specs ? { ...product.specs, ...hindiData.specs } : product.specs,
    ingredients: (product.ingredients || []).map(
      (ing) => INGREDIENT_HINDI_MAP[ing] || ing
    ),
  };
}
